#!/usr/bin/env python3
import collections
import os
import re
import sys

BASE_PACKAGE = 'com.credit.bladi'
SOURCES = 'src/main/java/' + BASE_PACKAGE.replace('.', '/')
OUTPUT = 'docs/dependency-graph.md'
IMPORT = re.compile(r'^import (?:static )?' + re.escape(BASE_PACKAGE) + r'\.([\w.]+);', re.M)


def package_of(path, depth):
    rel = os.path.relpath(os.path.dirname(path), SOURCES).split(os.sep)
    return '.'.join(rel[:depth]) if rel != ['.'] else '(root)'


def imported_package(target, depth):
    parts = target.split('.')
    packages = [p for p in parts if p[:1].islower()]
    return '.'.join(packages[:depth]) or '(root)'


def collect(depth, scope=None):
    edges = collections.Counter()
    nodes = collections.Counter()
    for folder, _, files in os.walk(SOURCES):
        for name in files:
            if not name.endswith('.java'):
                continue
            path = os.path.join(folder, name)
            source = package_of(path, depth)
            if scope and not source.startswith(scope):
                continue
            nodes[source] += 1
            text = open(path, encoding='utf-8').read()
            for target in IMPORT.findall(text):
                dest = imported_package(target, depth)
                if scope and not dest.startswith(scope):
                    continue
                if dest != source:
                    edges[(source, dest)] += 1
    return nodes, edges


def node_id(name):
    return 'n_' + re.sub(r'\W', '_', name)


def mermaid(nodes, edges, label):
    lines = ['```mermaid', 'flowchart LR']
    for name, count in sorted(nodes.items()):
        lines.append(f'    {node_id(name)}["{label(name)}<br/>{count} classes"]')
    for (source, dest), count in sorted(edges.items()):
        if dest in nodes:
            lines.append(f'    {node_id(source)} -->|{count}| {node_id(dest)}')
    lines.append('```')
    return '\n'.join(lines)


def main():
    layers, layer_edges = collect(1)
    services, service_edges = collect(2, 'service')
    page = [
        '# Dependency Graph (generated)',
        '',
        f'Generated by `python3 scripts/docs/dependency_graph.py` from the imports of `{SOURCES}`. Do not edit',
        'by hand: rerun the script after a refactoring. An arrow `A -->|n| B` means that `n` import statements in',
        'package `A` point to package `B`. The allowed directions are explained in',
        '[Architecture at a Glance](c4-architecture.md#backend-layers) and enforced by `ArchitectureTest`.',
        '',
        '## Top-level packages',
        '',
        mermaid(layers, layer_edges, lambda n: n),
        '',
        '## Inside `service`',
        '',
        mermaid(services, service_edges, lambda n: n.replace('service.', '', 1)),
        '',
    ]
    open(OUTPUT, 'w', encoding='utf-8').write('\n'.join(page))
    print(f'{OUTPUT}: {len(layers)} packages, {sum(layer_edges.values())} cross-package imports')
    return 0


if __name__ == '__main__':
    sys.exit(main())
